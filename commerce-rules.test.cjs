const assert=require('node:assert/strict'),R=require('../dist/commerce-rules.js');
const item=(pricePaise=10000,quantity=1,percent=0)=>({pricePaise,quantity,offer:{enabled:percent>0,percent}});
const bill={enabled:true,name:'Launch 5%',percent:5,minimumPaise:0,capPaise:0,stack:false};
let q=R.quote([item()],bill,1000);assert.equal(q.total,10500);assert.equal(q.billDiscount,500);assert.equal(q.deliveryPaise,1000);
q=R.quote([item(10000,1,10)],bill);assert.equal(q.total,9000);assert.equal(q.billDiscount,0);
q=R.quote([item(10000,1,2)],bill);assert.equal(q.total,9500);assert.equal(q.productDiscount,0);
q=R.quote([item(10000,1,10)],{...bill,stack:true});assert.equal(q.total,8550);
assert.equal(R.quote([item()],{...bill,minimumPaise:20000}).savings,0);
assert.equal(R.quote([item()],{...bill,capPaise:100}).savings,100);
assert.equal(R.quote([item()],{...bill,end:'2020-01-01'}).savings,0);
assert.equal(R.quote([item()],{...bill,start:'2099-01-01'}).savings,0);
assert.equal(R.active({...bill,start:'bad-date'}),false);
assert.equal(R.quote([item()],{...bill,percent:100}).total,0);
assert.throws(()=>R.quote([item()],{...bill,percent:101}));
q=R.quote([item(199),item(333),item(111,3)],{...bill,percent:17},101);
assert.equal(q.lines.reduce((n,l)=>n+l.net,0)+q.deliveryPaise,q.total);
assert.equal(q.lines.reduce((n,l)=>n+l.billDiscount,0),q.billDiscount);
assert.deepEqual(R.allocation(2,[1,1,1]),[1,1,0]);
const cfg={enabled:true,store:{lat:17.385,lng:78.4867},radius:5,freeKm:1,extraKmPaise:1000,free:false,pincodes:[]};
assert.equal(R.delivery(cfg,cfg.store).feePaise,0);
const near={lat:17.398,lng:78.4867};assert.equal(R.delivery(cfg,near).feePaise,1000);
assert.equal(R.delivery({...cfg,free:true},near).feePaise,0);
assert.equal(R.delivery(cfg,{lat:18,lng:78}).eligible,false);
assert.equal(R.delivery({...cfg,store:null},near).eligible,false);
assert.equal(R.delivery({...cfg,enabled:false},near).eligible,false);
assert.equal(R.delivery({...cfg,pincodes:['500001']},{...near,pincode:'500002'}).eligible,false);
assert.equal(R.delivery({...cfg,pincodes:['500001']},{...near,pincode:'500001'}).eligible,true);
assert.equal(R.point({lat:NaN,lng:78}),false);
assert.equal(R.point({lat:91,lng:78}),false);
assert.ok(Math.abs(R.km({lat:0,lng:0},{lat:0,lng:1})-111.195)<0.01);
console.log('PASS: offer arithmetic, best-offer selection, stacking, expiry, minimum, caps, paise allocation, geographic distance, delivery fees and area blocking.');
